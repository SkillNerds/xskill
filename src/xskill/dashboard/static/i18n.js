  let currentLanguage = 'zh';

  function interpolate(value, params) {
    if (!params) return value;
    return value.replace(/\{([a-zA-Z0-9_]+)\}/g, function (_match, name) {
      return Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : _match;
    });
  }

  function tr(key, params, language) {
    const locale = SUPPORTED.has(language) ? language : currentLanguage;
    const table = TRANSLATIONS[locale] || TRANSLATIONS.zh;
    const fallback = locale === 'zh' ? TRANSLATIONS.zh[key] : undefined;
    return interpolate(table[key] == null ? (fallback == null ? key : fallback) : table[key], params);
  }

  function applyStaticTranslations(root) {
    if (!global.document) return;
    const scope = root || global.document;
    scope.querySelectorAll('[data-i18n]').forEach(function (element) {
      element.textContent = tr(element.dataset.i18n);
    });
    for (const attribute of ['title', 'placeholder', 'aria-label']) {
      scope.querySelectorAll('[data-i18n-' + attribute + ']').forEach(function (element) {
        element.setAttribute(attribute, tr(element.getAttribute('data-i18n-' + attribute)));
      });
    }
  }

  function updateSwitch() {
    if (!global.document) return;
    global.document.querySelectorAll('[data-language]').forEach(function (button) {
      const active = button.dataset.language === currentLanguage;
      button.setAttribute('aria-pressed', String(active));
      button.classList.toggle('text-teal-700', active);
      button.classList.toggle('font-semibold', active);
      button.classList.toggle('text-slate-400', !active);
    });
  }

  function setLanguage(language, options) {
    const next = SUPPORTED.has(language) ? language : 'zh';
    const changed = next !== currentLanguage;
    currentLanguage = next;
    if (global.document) {
      global.document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN';
      applyStaticTranslations();
      global.document.title = tr('ui.xskill_console');
      updateSwitch();
    }
    if (!options || options.persist !== false) {
      try { global.localStorage.setItem(STORAGE_KEY, next); } catch (_error) { /* storage may be disabled */ }
    }
    if (changed && global.document && typeof global.CustomEvent === 'function') {
      global.document.dispatchEvent(new global.CustomEvent('xskill:languagechange', { detail: { language: next } }));
    }
    return next;
  }

  function init() {
    if (!global.document || !global.document.body) return;
    let saved = 'zh';
    try { saved = global.localStorage.getItem(STORAGE_KEY) || 'zh'; } catch (_error) { /* storage may be disabled */ }
    setLanguage(saved, { persist: false });
    global.document.addEventListener('click', function (event) {
      const button = event.target.closest && event.target.closest('[data-language]');
      if (button) setLanguage(button.dataset.language);
    });
  }

  global.XSkillI18n = {
    get language() { return currentLanguage; },
    setLanguage,
    tr,
    applyStaticTranslations,
    storageKey: STORAGE_KEY,
    translations: TRANSLATIONS
  };
  init();
